"""Build the Xtra Features plugin for Forza Horizon 2 Extra Options.

Usage: py plugins/xtra-features/build.py [--zig <zig.exe>] [--output out] [--test] [test options]
(the top-level build.py runs it with --output out/build/xtra-features)

Writes:
  <output>/mods/Xtra Features/mod.json
  <output>/mods/Xtra Features/plugins/XtraFeatures.dll
  <output>/mods/Xtra Features/plugins/XtraFeatures.ini
  <output>/tests/XtraFeaturesTest.dll   (the same code with test entry points)
--test also runs tests/run_tests.py on the result (it passes --game,
--azimuth and --release through). Nothing is installed.
Zig 0.15.2: --zig, else the ZIG environment variable, else zig on PATH.
"""

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "common"))
import build_common as bc  # noqa: E402

SRC = HERE / "src"
MOD_NAME = "Xtra Features"
DLL_NAME = "XtraFeatures.dll"
INI_NAME = "XtraFeatures.ini"
TEST_DLL = "XtraFeaturesTest.dll"
SOURCES = ["plugin.c", "settings.c", "patch.c", "map_zoom.c", "thumbnails.c", "photo_scan.c", "exit_game.c",
           "pause_xaml.c"]
# src/<json> -> obj/<header> with the array <name>: {language code, text}, EN first.
CAPTIONS = [("exit_game_captions.json", "exit_game_captions.h", "captions"),
            ("photo_scan_captions.json", "photo_scan_captions.h", "scan_captions")]


def generate(build, version):
    """obj/*_captions.h from src/*_captions.json, obj/version.rc from mod.json's version."""
    for source, header, name in CAPTIONS:
        captions = json.loads((SRC / source).read_text(encoding="utf-8"))
        if next(iter(captions), None) != "EN" or not all(isinstance(v, str) and v for v in captions.values()):
            sys.exit(f"src/{source}: EN first, one non-empty caption per language code")
        lines = [f"// Generated by build.py from src/{source}. Do not edit.\n",
                 "typedef struct { const char *code; const wchar_t *text; } Caption_%s;\n" % name,
                 "static const Caption_%s %s[] = {\n" % (name, name)]
        lines += ["    {%s, %s},\n" % (json.dumps(code), bc.wide_literal(text)) for code, text in captions.items()]
        lines.append("};\n")
        bc.write_if_changed(build / header, "".join(lines))
    bc.version_rc(build / "version.rc", version, DLL_NAME, "Xtra Features (Extra Options plugin)",
                  "Xtra Features for Forza Horizon 2")
    print(f"version {version}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    parser.add_argument("--game", type=Path, help="tests: the FH2 game folder (default ~/FH2)")
    parser.add_argument("--azimuth", type=Path, help="tests: the Azimuth 1.0.4 release ZIP")
    parser.add_argument("--release", type=Path, help="tests: Extra Options 0.4.4 release (its Azimuth folder)")
    options = parser.parse_args(argv)
    zig = bc.find_zig(options.zig)
    output = options.output.resolve()
    build = output / "obj"
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    tests = output / "tests"
    for folder in (plugins, tests, build):
        folder.mkdir(parents=True, exist_ok=True)
    version = bc.mod_version(HERE / "mod" / "mod.json")
    generate(build, version)

    common = [zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
              "-Wno-missing-field-initializers", "-fms-extensions", "-Wno-microsoft", "-funwind-tables", "-mcx16",
              "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE", f'-DXTRA_VERSION="{version}"',
              "-I", build, "-I", SRC, "-I", bc.INCLUDE]
    sources = [SRC / name for name in SOURCES]
    bc.run([*common, "-shared", "-s", *sources, build / "version.rc", "-luser32",
            "-Wl,--out-implib," + str(build / "plugin.lib"), "-o", plugins / DLL_NAME])
    bc.run([*common, "-shared", "-s", "-DXTRA_TEST", *sources, build / "version.rc", "-luser32",
            "-Wl,--out-implib," + str(build / "plugin-test.lib"), "-o", tests / TEST_DLL])
    for folder in (plugins, tests):
        for stale in list(folder.glob("*.lib")) + list(folder.glob("*.pdb")):
            stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / INI_NAME, plugins / INI_NAME)
    for path in (mod / "mod.json", plugins / DLL_NAME, plugins / INI_NAME, tests / TEST_DLL):
        print(path)
    if options.test:
        command = [sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output), "--zig", str(zig)]
        for name in ("game", "azimuth", "release"):
            if getattr(options, name):
                command += ["--" + name, str(getattr(options, name))]
        subprocess.run(command, check=True)


if __name__ == "__main__":
    main()
