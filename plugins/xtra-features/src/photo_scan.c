// Inspected game:
// - PhotoAnalysis (the page shown after a photo) runs 0xdb5b50: it takes the
//   view-0 camera ([[[0x34aba60]+0x50] locked by 0x2dd410]+0x2d0][0] vcall
//   +0x38, shared by 0x26ed00), queries the entities with a
//   PhotoChallengeComponent (0xcbdcd0) and, for each, calls 0x5dc4d0.
// - 0x5dc4d0 walks every car entity (0x499930 query) with the lambda 0x5d39c0
//   {&camera, component, &ordinals}: car ordinal 0xf60670, skips ordinal 1215
//   and MakeID 200, then the CPU visibility test 0x26d2c0 (frustum,
//   Min/MaxAllowedDistance, CarDetectionSphereRadius and occlusion rays) and
//   pushes visible ordinals. It then calls 0x5d8a00 (component, &new,
//   &detected), which credits each ordinal not yet in the collection (1000 CR
//   per car plus rank bonus, reason PhotoChallengeCarCapture), records it,
//   updates stats, raises PhotoChallengeCarPhotoed, saves the profile and
//   marks the component for its Update, which posts the "Cars photographed"
//   HUD notification. No rendered image is used: detection is geometric and
//   ray based.
// - The trigger is the photo mode page's own RB (UI key 0x14) handler, the
//   std::function registered by 0xdb4c40 (vtable 0x2e21b80, _Do_call 0xde8070
//   -> 0xdb1640). Page state [page+0x1194]: 0 camera, 1 effects panel, 2
//   hidden UI, 3 pre-save. The game uses RB only in states 1 (cycle vignette)
//   and 3 (watermark position); in 0 and 2 it is unbound. The scan answers RB
//   in states 0 and 2 only and hands the others to the previous _Do_call.
// - The native result: a real photo (A) goes to PreSave (0xdd0990), which
//   pushes the PhotoAnalysis scene through 0xddf250 (page): when
//   [page+0x1128] is 0 it creates scene kind 5 (PhotoAnalysis), which runs
//   the detection and credit itself and shows the game's own result. RB calls
//   0xddf250 directly in the camera view, without PreSave and without the
//   capture request, so no picture is taken or saved. In other flows
//   ([page+0x1128] set) the scan credits silently.
// - Help text: the photo mode button-bar update (0xde35c0) sets RB's text to
//   an empty string (call 0x140be20 at 0xde3735) outside the Effects panel.
//   That call is chained (patch.c chain_call; the fork used int3 padding) to
//   build "Scan cars" with 0x140af10 (UI string from a loc string) from a
