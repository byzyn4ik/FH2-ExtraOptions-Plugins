// One hooked vtable slot: per vtable, what the slot held before.
struct Method {
    const char *name;
    unsigned index;
    struct Slot {
        void **table;
        void *original;
    } slots[8];
    volatile LONG count;
};

void *original_for(Method &method, void *self) {
    LONG count = method.count;
    MemoryBarrier();
    void **table = self ? *(void ***)self : nullptr;
    for (LONG i = 0; i < count; ++i)
        if (method.slots[i].table == table) return method.slots[i].original;
    // An object whose vtable another module copied with our function in it.
    return count ? method.slots[0].original : nullptr;
}

SRWLOCK hook_lock = SRWLOCK_INIT;

bool patch(Method &method, void *object, void *callback, std::string *note) {
    void **table = *(void ***)object;
    AcquireSRWLockExclusive(&hook_lock);
    bool ok = false;
    LONG count = method.count;
    for (LONG i = 0; i < count; ++i)
        if (method.slots[i].table == table) ok = table[method.index] == callback;
    if (ok || count == (LONG)(sizeof(method.slots) / sizeof(method.slots[0]))) {
        ReleaseSRWLockExclusive(&hook_lock);
        return ok;
    }
    void *current = table[method.index];
    DWORD old, ignored;
    if (current && current != callback && VirtualProtect(table + method.index, sizeof(void *), PAGE_READWRITE, &old)) {
        method.slots[count] = {table, current};
        MemoryBarrier();
        InterlockedExchange(&method.count, count + 1);
        InterlockedExchangePointer(table + method.index, callback);
        VirtualProtect(table + method.index, sizeof(void *), old, &ignored);
        FlushInstructionCache(GetCurrentProcess(), table + method.index, sizeof(void *));
        ok = true;
        if (note) {
            std::string table_module = module_name(table), code_module = module_name(current);
            if (!note->empty()) *note += ", ";
            *note += std::string(method.name) + " (" + table_module + ")";
            if (code_module != table_module) *note += " chained onto " + code_module;
        }
    }
    ReleaseSRWLockExclusive(&hook_lock);
    return ok;
}

