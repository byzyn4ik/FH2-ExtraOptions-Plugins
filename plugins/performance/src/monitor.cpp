namespace {
std::wstring ini_value(const std::wstring &ini, const wchar_t *key) {
    wchar_t value[1024];
    GetPrivateProfileStringW(L"Performance", key, L"", value, 1024, ini.c_str());
    std::wstring text = value;
    while (!text.empty() && (text.back() == L' ' || text.back() == L'\t')) text.pop_back();
    size_t start = text.find_first_not_of(L" \t");
    return start == std::wstring::npos ? std::wstring() : text.substr(start);
}
} // namespace

Options read_options(const std::wstring &ini, const std::wstring &folder, std::string *warnings) {
    Options o;
    o.ini = ini;
    std::wstring show = ini_value(ini, L"ShowFps"), log = ini_value(ini, L"PerfLog"),
                 row = ini_value(ini, L"MenuRow"), file = ini_value(ini, L"PerfLogFile");
    auto warn = [&](const char *key, const std::wstring &value, const char *kept) {
        if (warnings)
            *warnings += std::string(warnings->empty() ? "" : "; ") + key + "=" + narrow(value) +
                         " is not valid, " + kept;
    };
    if (show == L"0" || show == L"1" || show == L"2")
        o.show = (unsigned)(show[0] - L'0');
    else if (!show.empty())
        warn("ShowFps", show, "1 is used (0 off, 1 FPS, 2 detailed)");
    if (log == L"0" || log == L"1")
        o.log = log == L"1";
    else if (!log.empty())
        warn("PerfLog", log, "0 is used (0 off, 1 on)");
    if (row == L"0" || row == L"1")
        o.row = row == L"1";
    else if (!row.empty())
        warn("MenuRow", row, "1 is used (0 off, 1 on)");
    bool absolute = file.size() > 1 && (file[1] == L':' || (file[0] == L'\\' && file[1] == L'\\'));
    if (file.empty())
        o.csv = folder + L"\\fh2-perf.csv";
    else
        o.csv = absolute || folder.empty() ? file : folder + L"\\" + file;
    return o;
}

bool write_show(const std::wstring &ini, unsigned mode) {
    wchar_t value[2] = {wchar_t(L'0' + (mode > 2 ? 1 : mode)), 0};
    return WritePrivateProfileStringW(L"Performance", L"ShowFps", value, ini.c_str()) != 0;
}

