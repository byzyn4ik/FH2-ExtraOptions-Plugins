void configure(const Options &options) {
    Hold hold;
    if (is_configured) return;
    is_configured = true;
    QueryPerformanceFrequency(&frequency);
    overlay = options.show;
    ini_path = options.ini;
    size_t slash = ini_path.find_last_of(L"\\/");
    ini_folder = slash == std::wstring::npos ? std::wstring() : ini_path.substr(0, slash);
    WIN32_FILE_ATTRIBUTE_DATA data;
    if (!ini_path.empty() && GetFileAttributesExW(ini_path.c_str(), GetFileExInfoStandard, &data))
        ini_time = data.ftLastWriteTime;
    LARGE_INTEGER start;
    QueryPerformanceCounter(&start);
    session_start = start.QuadPart;
    SYSTEMTIME t;
    GetLocalTime(&t);
    snprintf(session, sizeof(session), "%04u%02u%02u-%02u%02u%02u", t.wYear, t.wMonth, t.wDay, t.wHour, t.wMinute,
             t.wSecond);
    csv_path = options.csv;
    if (options.log) open_csv();
    csv_enabled = options.log && csv != INVALID_HANDLE_VALUE;
}

bool configured() {
    Hold hold;
    return is_configured;
}

void set_show(unsigned mode) {
    if (mode > kShowDetailed) mode = kShowFps;
    if (overlay.exchange(mode) != mode) {
        Hold hold;
        last_text = 0; // new text at the next Present
    }
}

unsigned show() { return overlay.load(); }

void set_log(bool on) {
    Hold hold;
    if (on)
        open_csv();
    else
        close_csv();
    csv_enabled = on && csv != INVALID_HANDLE_VALUE;
}

bool hook_factory(IDXGIFactory *factory, std::string *note) {
    bool ok = patch(make_old_method, factory, (void *)make_old_chain, note);
    IDXGIFactory2 *two{};
    if (SUCCEEDED(factory->QueryInterface(IID_PPV_ARGS(&two)))) {
        ok = patch(make_method, two, (void *)make_chain, note) && ok;
        two->Release();
    }
    return ok;
}

bool hook_swap_chain(IDXGISwapChain *chain, std::string *note) {
    bool ok = patch(present_method, chain, (void *)present, note);
    IDXGISwapChain1 *one{};
    if (SUCCEEDED(chain->QueryInterface(IID_PPV_ARGS(&one)))) {
        // IDXGISwapChain1 is the same object and vtable in DXGI; anything else is left alone.
        if (*(void ***)one == *(void ***)chain) ok = patch(present1_method, chain, (void *)present1, note) && ok;
        one->Release();
    }
    IDXGISwapChain3 *third{};
    if (SUCCEEDED(chain->QueryInterface(IID_PPV_ARGS(&third)))) {
        if (*(void ***)third == *(void ***)chain) patch(color_method, chain, (void *)color_space, note);
        third->Release();
    }
    return ok;
}

bool hook_queue(ID3D12CommandQueue *queue, std::string *note) {
    return queue && patch(execute_method, queue, (void *)execute, note);
}

void stats(Stats *out) {
    if (!out || out->size < sizeof(Stats)) return;
    LARGE_INTEGER now;
    QueryPerformanceCounter(&now);
    Hold hold;
    Stats s{};
    s.size = sizeof(Stats);
    s.presents = presents_seen;
    s.measured = measured_frames;
    s.chains = chain_count;
    s.bound_serial = bound == NONE ? 0 : chains[bound].serial;
    s.overlays = overlays_drawn;
    s.gpu_samples = gpu_samples;
    s.csv_lines = csv_lines;
    s.gpu_failed = gpu_failed;
    s.show = overlay.load();
    s.ini_reloads = ini_reloads;
    s.created = created_seen;
    if (frequency.QuadPart) {
        FrameStats recent = frame_stats(now.QuadPart - frequency.QuadPart / 2);
        s.fps = recent.frames && recent.avg_ms > 0 ? 1000.0 / recent.avg_ms : 0;
        unsigned samples = 0;
        gpu_average(now.QuadPart - frequency.QuadPart / 2, s.gpu_ms, samples);
    }
    static_assert(sizeof(s.text[0]) > COLUMNS, "stats text lines");
    for (unsigned l = 0; l < LINES; ++l) memcpy(s.text[l], text[l], COLUMNS);
    *out = s;
}

