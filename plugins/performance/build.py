"""Build the Performance plugin for Forza Horizon 2 Extra Options.

Usage: py plugins/performance/build.py [--zig <zig.exe>] [--output out] [--test] [test options]
(the top-level build.py runs it with --output out/build/performance)

Writes:
  <output>/mods/Performance/mod.json
  <output>/mods/Performance/plugins/Performance.dll
  <output>/mods/Performance/plugins/Performance.ini
  <output>/tests/PerformanceTest.dll   (the same code with test entry points)
  <output>/tests/d3d12_test.exe        (the in-process D3D12 test)
The overlay's shaders (src/overlay.hlsl) are compiled here with Windows'
d3dcompiler_47.dll into obj/overlay_shaders.h; nothing is compiled in the game.
--test also runs tests/run_tests.py on the result (it passes --game,
--azimuth, --upstream, --graphics and --warp through). Nothing is installed.
Zig 0.15.2: --zig, else the ZIG environment variable, else zig on PATH.
"""

import argparse
import ctypes
import json
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "common"))
import build_common as bc  # noqa: E402

SRC = HERE / "src"
MOD_NAME = "Performance"
DLL_NAME = "Performance.dll"
INI_NAME = "Performance.ini"
TEST_DLL = "PerformanceTest.dll"
SOURCES = ["common.cpp", "monitor.cpp", "attach.cpp", "call_chain.cpp", "video_row.cpp", "plugin.cpp"]
LIBRARIES = ["-ld3d12", "-ldxgi", "-ldxguid", "-luser32"]


def compile_shader(source, entry, target):
    """HLSL to DXBC with d3dcompiler_47.dll (D3DCOMPILE_ENABLE_STRICTNESS | OPTIMIZATION_LEVEL3)."""
    compiler = ctypes.WinDLL("d3dcompiler_47")
    compile_ = compiler.D3DCompile
    compile_.restype = ctypes.c_long
    compile_.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                         ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                         ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    hr = compile_(source, len(source), b"overlay.hlsl", None, None, entry.encode(), target.encode(),
                  0x800 | 0x8000, 0, ctypes.byref(code), ctypes.byref(errors))

    def blob(pointer):
        table = ctypes.cast(ctypes.cast(pointer, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
        release = ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(table[2])
        data = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(table[3])(pointer)
        size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(table[4])(pointer)
        result = ctypes.string_at(data, size)
        release(pointer)
        return result

    message = blob(errors).decode("utf-8", "replace") if errors.value else ""
    if hr < 0 or not code.value:
        sys.exit(f"src/overlay.hlsl ({entry}, {target}): {message or hex(hr & 0xffffffff)}")
    if message.strip():
        sys.exit(f"src/overlay.hlsl ({entry}, {target}) has warnings:\n{message}")
    return blob(code)


def generate(build, version):
    """obj/translations.h, obj/overlay_shaders.h and obj/version.rc."""
    captions = json.loads((SRC / "translations.json").read_text(encoding="utf-8"))
    if next(iter(captions), None) != "EN" or not all(
            isinstance(v, dict) and isinstance(v.get("name"), str) and v["name"] and isinstance(v.get("description"), str)
            and isinstance(v.get("choices"), list) and len(v["choices"]) == 3 and all(isinstance(c, str) and c for c in v["choices"])
            for v in captions.values()):
        sys.exit("src/translations.json: EN first; per language code a name, three choices and a description")
    lines = ["// Generated by build.py from src/translations.json. Do not edit.\n",
             "static const perf::video_row::Captions kCaptions[] = {\n"]
    for code, c in captions.items():
        lines.append("    {%s, %s, {%s}, %s},\n" % (json.dumps(code), bc.wide_literal(c["name"]),
                                                   ", ".join(bc.wide_literal(x) for x in c["choices"]),
                                                   bc.wide_literal(c["description"])))
    lines.append("};\n")
    bc.write_if_changed(build / "translations.h", "".join(lines))

    source = (SRC / "overlay.hlsl").read_bytes()
    parts = ["// Generated by build.py from src/overlay.hlsl (d3dcompiler_47). Do not edit.\n"]
    for name, entry, target in (("kOverlayVs", "vs", "vs_5_0"), ("kOverlayPs", "ps", "ps_5_0")):
        code = compile_shader(source, entry, target)
        rows = [", ".join("0x%02x" % b for b in code[i:i + 16]) for i in range(0, len(code), 16)]
        parts.append("static const unsigned char %s[%d] = {\n    %s};\n" % (name, len(code), ",\n    ".join(rows)))
    bc.write_if_changed(build / "overlay_shaders.h", "".join(parts))

    bc.version_rc(build / "version.rc", version, DLL_NAME, "Performance (Extra Options plugin)",
                  "Performance for Forza Horizon 2")
    print(f"captions: {len(captions)} language codes; shaders compiled; version {version}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    parser.add_argument("--game", type=Path, help="tests: the FH2 game folder (default ~/FH2)")
    parser.add_argument("--azimuth", type=Path, help="tests: the Azimuth 1.0.4 release ZIP")
    parser.add_argument("--upstream", type=Path, help="tests: Extra Options 0.4.4 source (a git checkout)")
    parser.add_argument("--graphics", type=Path, help="tests: the Azimuth Graphics Options plugin source")
    parser.add_argument("--warp", action="store_true", help="tests: the D3D12 test on WARP even with a GPU")
    options = parser.parse_args(argv)
    zig = bc.find_zig(options.zig)
    output = options.output.resolve()
    build = output / "obj"
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    tests = output / "tests"
    for folder in (plugins, tests, build):
        folder.mkdir(parents=True, exist_ok=True)
    version = bc.mod_version(HERE / "mod" / "mod.json")
    generate(build, version)

    common = [zig, "c++", "-target", "x86_64-windows-gnu", "-std=c++17", "-O2", "-Wall", "-Wextra", "-Werror",
              "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE", "-DWIDL_EXPLICIT_AGGREGATE_RETURNS", f'-DPERFORMANCE_VERSION="{version}"',
              "-I", build, "-I", SRC, "-I", bc.INCLUDE]
    sources = [SRC / name for name in SOURCES]
    bc.run([*common, "-shared", "-s", *sources, build / "version.rc", *LIBRARIES,
         "-Wl,--out-implib," + str(build / "plugin.lib"), "-o", plugins / DLL_NAME])
    bc.run([*common, "-shared", "-s", "-DPERFORMANCE_TEST", *sources, build / "version.rc", *LIBRARIES,
         "-Wl,--out-implib," + str(build / "plugin-test.lib"), "-o", tests / TEST_DLL])
    bc.run([*common, "-municode", "-s", HERE / "tests" / "d3d12_test.cpp", *LIBRARIES, "-o", tests / "d3d12_test.exe"])
    for folder in (plugins, tests):
        for stale in list(folder.glob("*.lib")) + list(folder.glob("*.pdb")):
            stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / INI_NAME, plugins / INI_NAME)
    for path in (mod / "mod.json", plugins / DLL_NAME, plugins / INI_NAME, tests / TEST_DLL, tests / "d3d12_test.exe"):
        print(path)
    if options.test:
        command = [sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output), "--zig", str(zig)]
        for name in ("game", "azimuth", "upstream", "graphics"):
            if getattr(options, name):
                command += ["--" + name, str(getattr(options, name))]
        if options.warp:
            command.append("--warp")
        subprocess.run(command, check=True)


if __name__ == "__main__":
    main()
