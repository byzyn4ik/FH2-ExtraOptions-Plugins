"""Build the Keyboard & Mouse plugin for Forza Horizon 2 Extra Options.

Usage: py build.py [--zig <zig.exe>] [--output out] [--test] [test options]

Writes:
  <output>/mods/Keyboard & Mouse/mod.json
  <output>/mods/Keyboard & Mouse/plugins/KeyboardMouse.dll
  <output>/mods/Keyboard & Mouse/plugins/KeyboardMouse.ini
  <output>/tests/KeyboardMouseTest.dll   (the same code with test entry points)
--test also runs tests/run_tests.py on the result (it passes --game,
--azimuth, --azimuth102, --upstream and --release through). Nothing is
installed. Zig 0.15.2: --zig, else the ZIG environment variable, else zig on
PATH.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
MOD_NAME = "Keyboard & Mouse"
DLL_NAME = "KeyboardMouse.dll"
INI_NAME = "KeyboardMouse.ini"
TEST_DLL = "KeyboardMouseTest.dll"
SOURCES = ["plugin.c", "common.c", "patch.c", "host.c", "settings.c", "eo_bindings.c", "kbm_config.c",
           "kbm_input.c", "kbm_win32.c", "kbm_pitch.c", "kbm_rebind.c", "kbm_menu.c", "kbm_text.c",
           "settings_page.c", "controller_pause.c"]
LIBRARIES = ["-luser32", "-lgdi32"]
LANGUAGES = ["EN", "GB", "BR", "DE", "FR", "ES", "MX", "IT", "JP", "KO", "CHT", "CZ", "HU", "PL", "RU", "NL"]
COUNTS = {"rows": 9, "descriptions": 9, "modes": 3, "actions": 33, "key_descriptions": 2, "labels": 8}


def find_zig(given):
    for candidate in (given, os.environ.get("ZIG"), shutil.which("zig")):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    sys.exit("zig not found: pass --zig <zig.exe> (Zig 0.15.2) or set ZIG")


def wide_literal(text):
    out = []
    for ch in text:
        code = ord(ch)
        if 0x20 <= code < 0x7f and ch not in '"\\?':
            out.append(ch)
        elif code < 0xa0:
            out.append("\\%03o" % code)  # \u may not name these
        elif code > 0xffff:
            out.append("\\U%08x" % code)
        else:
            out.append("\\u%04x" % code)
    return 'L"' + "".join(out) + '"'


def utf8_literal(text):
    """A narrow literal holding the UTF-8 bytes (octal escapes: never merged with what follows)."""
    out = []
    for byte in text.encode("utf-8"):
        if 0x20 <= byte < 0x7f and chr(byte) not in '"\\?':
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def write_if_changed(path, text):
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def generate(build, version):
    """obj/translations.h from src/translations.json, obj/version.rc from mod.json's version."""
    texts = json.loads((SRC / "translations.json").read_text(encoding="utf-8"))
    if list(texts) != LANGUAGES:
        sys.exit("src/translations.json: the language codes " + " ".join(LANGUAGES) + ", in that order")
    for code, entry in texts.items():
        for key, count in COUNTS.items():
            if len(entry.get(key, [])) != count or not all(isinstance(v, str) and v for v in entry[key]):
                sys.exit(f"src/translations.json: {code}.{key} needs {count} non-empty texts")
        for key in ("title", "reset", "reset_description", "on", "off"):
            if not isinstance(entry.get(key), str) or not entry[key]:
                sys.exit(f"src/translations.json: {code}.{key} is missing")
    narrow = lambda values: "{" + ", ".join(utf8_literal(v) for v in values) + "}"
    wide = lambda values: "{" + ", ".join(wide_literal(v) for v in values) + "}"
    lines = ["// Generated by build.py from src/translations.json. Do not edit.\n",
             "static const KbmText kbm_texts[] = {\n"]
    for code, e in texts.items():
        lines.append(
            f"    {{{json.dumps(code)}, {utf8_literal(e['title'])},\n"
            f"     {narrow(e['rows'])},\n     {narrow(e['descriptions'])},\n     {wide(e['modes'])},\n"
            f"     {narrow(e['actions'])},\n     {narrow(e['key_descriptions'])},\n"
            f"     {utf8_literal(e['reset'])}, {utf8_literal(e['reset_description'])},\n"
            f"     {wide(e['labels'])}, {wide_literal(e['on'])}, {wide_literal(e['off'])}}},\n")
    lines.append("};\n")
    write_if_changed(build / "translations.h", "".join(lines))
    numbers = (version.split(".") + ["0"] * 4)[:4]
    rc = f"""// Generated by build.py from mod/mod.json. Do not edit.
1 VERSIONINFO
FILEVERSION {",".join(numbers)}
PRODUCTVERSION {",".join(numbers)}
FILEOS 0x40004
FILETYPE 0x2
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "FileDescription", "Keyboard & Mouse (Extra Options plugin)"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "KeyboardMouse"
      VALUE "OriginalFilename", "{DLL_NAME}"
      VALUE "ProductName", "Keyboard & Mouse for Forza Horizon 2"
      VALUE "ProductVersion", "{version}"
      VALUE "LegalCopyright", "Max Petrovsky (byzyn4ik), GPL-3.0-or-later"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"""
    write_if_changed(build / "version.rc", rc)
    print(f"texts: {len(texts)} language codes; version {version}")


def run(command):
    print("zig", *[Path(str(part)).name if str(part).endswith((".c", ".rc", ".dll")) else str(part)
                   for part in command[1:]])
    subprocess.run([str(part) for part in command], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    parser.add_argument("--game", type=Path, help="tests: the FH2 game folder (default ~/FH2)")
    parser.add_argument("--azimuth", type=Path, help="tests: the Azimuth 1.0.4 release ZIP")
    parser.add_argument("--azimuth102", type=Path, help="tests: the Azimuth 1.0.2 release ZIP")
    parser.add_argument("--upstream", type=Path, help="tests: Extra Options 0.4.4 source (a git checkout)")
    parser.add_argument("--release", type=Path, help="tests: Extra Options 0.4.4 release (its Azimuth folder)")
    options = parser.parse_args()
    zig = find_zig(options.zig)
    output = options.output.resolve()
    build = output / "obj"
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    tests = output / "tests"
    for folder in (plugins, tests, build):
        folder.mkdir(parents=True, exist_ok=True)
    version = json.loads((HERE / "mod" / "mod.json").read_text(encoding="utf-8"))["version"]
    generate(build, version)

    common = [zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
              "-Wno-missing-field-initializers", "-fms-extensions", "-Wno-microsoft", "-funwind-tables",
              "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE", f'-DKBM_VERSION="{version}"', "-I", build, "-I", SRC]
    sources = [SRC / name for name in SOURCES]
    run([*common, "-shared", "-s", *sources, build / "version.rc", *LIBRARIES,
         "-Wl,--out-implib," + str(build / "plugin.lib"), "-o", plugins / DLL_NAME])
    run([*common, "-shared", "-s", "-DKBM_TEST", *sources, build / "version.rc", *LIBRARIES,
         "-Wl,--out-implib," + str(build / "plugin-test.lib"), "-o", tests / TEST_DLL])
    for folder in (plugins, tests):
        for stale in list(folder.glob("*.lib")) + list(folder.glob("*.pdb")):
            stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / INI_NAME, plugins / INI_NAME)
    for path in (mod / "mod.json", plugins / DLL_NAME, plugins / INI_NAME, tests / TEST_DLL):
        print(path)
    if options.test:
        command = [sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output), "--zig", str(zig)]
        for name in ("game", "azimuth", "azimuth102", "upstream", "release"):
            if getattr(options, name):
                command += ["--" + name, str(getattr(options, name))]
        subprocess.run(command, check=True)


if __name__ == "__main__":
    main()
