"""Build the Exit Game plugin for Forza Horizon 2 Extra Options.

Usage: py build.py [--zig <zig.exe>] [--output out] [--test] [test options]

Writes:
  <output>/mods/Exit Game/mod.json
  <output>/mods/Exit Game/plugins/ExitGame.dll
  <output>/mods/Exit Game/plugins/ExitGame.ini
  <output>/tests/ExitGameTest.dll   (the same code with test entry points)
--test also runs tests/run_tests.py on the result (it passes --game,
--azimuth and --upstream through). Nothing is installed.
Zig 0.15.2: --zig, else the ZIG environment variable, else zig on PATH.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
MOD_NAME = "Exit Game"
DLL_NAME = "ExitGame.dll"
INI_NAME = "ExitGame.ini"
SOURCES = ["plugin.c", "hooks.c", "pause_xaml.c"]


def find_zig(given):
    for candidate in (given, os.environ.get("ZIG"), shutil.which("zig")):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    sys.exit("zig not found: pass --zig <zig.exe> (Zig 0.15.2) or set ZIG")


def wide_literal(text):
    out = []
    for ch in text:
        code = ord(ch)
        if 0x20 <= code < 0x7f and ch not in '"\\':
            out.append(ch)
        elif code > 0xffff:
            out.append("\\U%08x" % code)
        else:
            out.append("\\u%04x" % code)
    return 'L"' + "".join(out) + '"'


def write_if_changed(path, text):
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def generate(build, version):
    """obj/translations.h from src/translations.json, obj/version.rc from mod.json's version."""
    captions = json.loads((SRC / "translations.json").read_text(encoding="utf-8"))
    if next(iter(captions), None) != "EN" or not all(isinstance(v, str) and v for v in captions.values()):
        sys.exit("src/translations.json: EN first, one non-empty caption per language code")
    lines = ["// Generated by build.py from src/translations.json. Do not edit.\n",
             "typedef struct { const char *code; const wchar_t *text; } Caption;\n",
             "static const Caption captions[] = {\n"]
    lines += ["    {%s, %s},\n" % (json.dumps(code), wide_literal(text)) for code, text in captions.items()]
    lines.append("};\n")
    write_if_changed(build / "translations.h", "".join(lines))
    numbers = (version.split(".") + ["0"] * 4)[:4]
    rc = f"""// Generated by build.py from mod/mod.json. Do not edit.
1 VERSIONINFO
FILEVERSION {",".join(numbers)}
PRODUCTVERSION {",".join(numbers)}
FILEOS 0x40004
FILETYPE 0x2
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "FileDescription", "Exit Game (Extra Options plugin)"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "ExitGame"
      VALUE "OriginalFilename", "{DLL_NAME}"
      VALUE "ProductName", "Exit Game for Forza Horizon 2"
      VALUE "ProductVersion", "{version}"
      VALUE "LegalCopyright", "Max Petrovsky (byzyn4ik), GPL-3.0-or-later"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"""
    write_if_changed(build / "version.rc", rc)
    print(f"captions: {len(captions)} language codes; version {version}")


def run(command):
    print("zig", *[Path(str(part)).name if str(part).endswith((".c", ".rc", ".dll")) else str(part)
                   for part in command[1:]])
    subprocess.run([str(part) for part in command], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    parser.add_argument("--game", type=Path, help="tests: the FH2 game folder (default ~/FH2)")
    parser.add_argument("--azimuth", type=Path, help="tests: the Azimuth 1.0.4 release ZIP")
    parser.add_argument("--upstream", type=Path, help="tests: Extra Options 0.4.4 source (a git checkout)")
    options = parser.parse_args()
    zig = find_zig(options.zig)
    output = options.output.resolve()
    build = output / "obj"
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    tests = output / "tests"
    for folder in (plugins, tests, build):
        folder.mkdir(parents=True, exist_ok=True)
    version = json.loads((HERE / "mod" / "mod.json").read_text(encoding="utf-8"))["version"]
    generate(build, version)

    common = [zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
              "-Wno-missing-field-initializers", "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE",
              f'-DEXIT_GAME_VERSION="{version}"', "-I", build, "-I", SRC]
    sources = [SRC / name for name in SOURCES]
    run([*common, "-shared", "-s", *sources, build / "version.rc", "-luser32",
         "-Wl,--out-implib," + str(build / "plugin.lib"), "-o", plugins / DLL_NAME])
    run([*common, "-shared", "-s", "-DEXIT_GAME_TEST", *sources, build / "version.rc", "-luser32",
         "-Wl,--out-implib," + str(build / "plugin-test.lib"), "-o", tests / "ExitGameTest.dll"])
    for folder in (plugins, tests):
        for stale in list(folder.glob("*.lib")) + list(folder.glob("*.pdb")):
            stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / INI_NAME, plugins / INI_NAME)
    for path in (mod / "mod.json", plugins / DLL_NAME, plugins / INI_NAME, tests / "ExitGameTest.dll"):
        print(path)
    if options.test:
        command = [sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output), "--zig", str(zig)]
        for name in ("game", "azimuth", "upstream"):
            if getattr(options, name):
                command += ["--" + name, str(getattr(options, name))]
        subprocess.run(command, check=True)


if __name__ == "__main__":
    main()
