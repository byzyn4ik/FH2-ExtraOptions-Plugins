"""Build helpers shared by the plugins' build.py scripts (and the top-level build.py)."""

import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

COMMON = Path(__file__).resolve().parent
ROOT = COMMON.parent
INCLUDE = COMMON / "include"  # fh2_plugin.h (the Extra Options plugin API), fh2_guard.h, fh2_game.h


def find_zig(given):
    """Zig 0.15.2: `given`, else the ZIG environment variable, else zig on PATH."""
    for candidate in (given, os.environ.get("ZIG"), shutil.which("zig")):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    sys.exit("zig not found: pass --zig <zig.exe> (Zig 0.15.2) or set ZIG")


def show(command):
    """Prints a command with its path arguments shortened to their file names."""
    print(" ".join(Path(str(part)).name if os.sep in str(part) or "/" in str(part) else str(part)
                   for part in command), flush=True)


def run(command):
    show(command)
    subprocess.run([str(part) for part in command], check=True)


def write_if_changed(path, text):
    """Writes a generated file only when its text changes (keeps rebuilds incremental)."""
    path = Path(path)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def mod_version(mod_json):
    return json.loads(Path(mod_json).read_text(encoding="utf-8"))["version"]


def wide_literal(text):
    """A C wide string literal for `text` (ASCII kept, the rest as \\u escapes)."""
    out = []
    for ch in text:
        code = ord(ch)
        if 0x20 <= code < 0x7f and ch not in '"\\':
            out.append(ch)
        elif code > 0xffff:
            out.append("\\U%08x" % code)
        else:
            out.append("\\u%04x" % code)
    return 'L"' + "".join(out) + '"'


def version_rc(path, version, dll_name, description, product):
    """A VERSIONINFO resource script for the plugin DLL, from mod.json's version."""
    numbers = (version.split(".") + ["0"] * 4)[:4]
    internal = Path(dll_name).stem
    rc = f"""// Generated by build.py from mod/mod.json. Do not edit.
1 VERSIONINFO
FILEVERSION {",".join(numbers)}
PRODUCTVERSION {",".join(numbers)}
FILEOS 0x40004
FILETYPE 0x2
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "FileDescription", "{description}"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "{internal}"
      VALUE "OriginalFilename", "{dll_name}"
      VALUE "ProductName", "{product}"
      VALUE "ProductVersion", "{version}"
      VALUE "LegalCopyright", "Max Petrovsky (byzyn4ik), GPL-3.0-or-later"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"""
    write_if_changed(path, rc)
    return Path(path)
